#!/usr/bin/env python3
"""Per-class metrics of one QOS run, written as small CSV files so the raw logs can be deleted.

    tools/qos/metrics.py <run folder> <trace folder> [--warmup 2] [--range 300] [--out <folder>]

Every metric is computed per traffic class (flow) and, where it makes sense, per Tx-Rx distance bin.
docs/notebooks/10_qos_definitions.ipynb defines each one; the short version:

  attempt      a packet generated by node i and a node j that was active and within --max-distance
               of i at the generation time. Packets the MAC never sent are attempts too.
  PDR          decoded attempts / attempts (any copy of the packet decoded)
  QoS-PDR      attempts decoded within the PDB of the class (plus the slot the reception ends in)
               / attempts. 1 - QoS-PDR is the
               measured PER, to compare with the PER of the PQI
  PIR          time between two consecutive decoded packets of one class, same Tx-Rx pair
  DT           Rolich et al. 2026: a PIR interval that contains at least one lost attempt
  AoI          time average of the age of the freshest packet of the class at the receiver
  collision    attempts lost with lossType 3 (another sidelink TB overlapped in time and frequency)
  CBR          per UE and per 100 ms, from CBR_OutputFile.txt
  occupancy    subchannel-slots used by the class / subchannel-slots available
  re-evaluations and pre-emptions: checks and resource changes, per class
  root cause   one cause per failed attempt, see CAUSES
  HNIR         hidden-node impact ratio: attempts lost to a collision in which every interfering
               transmitter was hidden from the sender (the sender decoded none of its packets in the
               1.1 s before), over all attempts. HNCR is the same count over all collisions
"""
import argparse
import json
import os
import sys

import numpy as np
import pandas as pd

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import morev2x_results as mr  # noqa: E402

APP_COLUMNS = ["packet", "node", "flow", "pqi", "priority", "genTime", "size", "pdb"]
FLOW_COLUMNS = ["flow", "name", "pqi", "priority", "pdb", "per", "gbr", "scheduling", "rri", "l2", "retx"]
DROP_COLUMNS = ["node", "time", "packet", "genTime", "pdb", "bytes", "reason"]
SENSING_WINDOW = 1.1  # s, TS 38.214 sensing window at RRI <= 1000 ms

CAUSES = ["decoded in time", "late (decoded after the PDB)", "oversize drop", "intra-UE conflict",
          "replaced by a newer packet", "never transmitted", "half duplex", "below sensitivity", "propagation", "hidden-node collision",
          "sensing-visible collision", "injected burst"]
DISTANCE_BINS = list(range(0, 1001, 50))


def read(folder, name, columns):
    path = os.path.join(folder, name)
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        return pd.DataFrame(columns=columns)
    return pd.read_csv(path, header=None, names=columns)


class Positions:
    """Positions of every node over time, from the trace the run replayed."""

    def __init__(self, trace_folder, first_node_id):
        trace = pd.read_csv(os.path.join(trace_folder, "trace.csv"))
        trace["node"] = trace.node_id + first_node_id
        self.times = np.sort(trace.time.unique())
        self.step = float(np.median(np.diff(self.times))) if len(self.times) > 1 else 0.1
        self.table = {t: g.set_index("node")[["x", "y"]] for t, g in trace.groupby("time")}

    def at(self, time):
        """x, y of the nodes present at the trace sample nearest to time."""
        index = int(np.clip(np.round(time / self.step), 0, len(self.times) - 1))
        return self.table[self.times[index]]


def attempts_table(run, app, flows, positions, max_distance, warmup, sim_end, slot_ms=0.25):
    """One row per (packet, receiver in range): flow, distance, outcome and its time."""
    rx = run.rx.copy()
    rx["receptionTime"] = rx.rxTime
    # one row per packet and receiver: decoded if any copy decoded, earliest decoded copy wins
    rx = rx.sort_values(["decoded", "receptionTime"], ascending=[False, True])
    best = rx.drop_duplicates(["packetID", "rxID"])
    app = app[(app.genTime >= warmup) & (app.genTime <= sim_end - 0.2)]
    transmitted = set(run.tx.packet.unique())

    # Positions at the trace sample nearest to each generation time, one distance matrix per sample
    sample = np.clip(np.round(app.genTime.to_numpy() / positions.step), 0, len(positions.times) - 1).astype(int)
    chunks = []
    for k, group in app.groupby(sample):
        here = positions.table[positions.times[k]]
        nodes = here.index.to_numpy()
        xs, ys = here.x.to_numpy(), here.y.to_numpy()
        where = pd.Index(nodes).get_indexer(group.node.to_numpy())
        group = group[where >= 0]
        where = where[where >= 0]
        if not len(group):
            continue
        distance = np.hypot(xs[None, :] - xs[where][:, None], ys[None, :] - ys[where][:, None])
        within = (distance <= max_distance) & (nodes[None, :] != group.node.to_numpy()[:, None])
        r, c = np.nonzero(within)
        chunks.append(pd.DataFrame({"packet": group.packet.to_numpy()[r], "tx": group.node.to_numpy()[r],
                                    "rx": nodes[c].astype(np.int64), "flow": group.flow.to_numpy()[r],
                                    "genTime": group.genTime.to_numpy()[r], "distance": distance[r, c]}))
    columns = ["packet", "tx", "rx", "flow", "genTime", "distance"]
    attempts = pd.concat(chunks, ignore_index=True) if chunks else pd.DataFrame(columns=columns)
    attempts["transmitted"] = attempts.packet.isin(transmitted)
    attempts = attempts.merge(best[["packetID", "rxID", "decoded", "lossType", "latency", "receptionTime", "txIndex"]],
                              left_on=["packet", "rx"], right_on=["packetID", "rxID"], how="left")
    attempts = attempts.drop(columns=["packetID", "rxID"])
    attempts["decoded"] = attempts.decoded.fillna(0).astype(int)
    pdb = flows.set_index("flow").pdb / 1000.0
    attempts["pdb"] = attempts.flow.map(pdb)
    # The selection window ends with the slot that contains generation + PDB, and a reception is
    # complete at the end of its slot: one slot of tolerance, otherwise the last slot of every
    # window would count as late
    attempts["inTime"] = (attempts.decoded == 1) & (attempts.latency.astype("float64") <= attempts.pdb + slot_ms / 1000.0 + 1e-6)
    return attempts


def hidden_collisions(run, collided, slot):
    """For each collided attempt: were all its interferers hidden from the sender?

    Interferers are the other transmissions in the same slot whose RBs overlap (phyDebugShort.txt).
    Interferer k is hidden from sender i when i decoded none of k's packets in the SENSING_WINDOW
    before the generation of the collided packet. Returns a boolean Series on collided.index.
    """
    if not len(collided):
        return pd.Series(False, index=collided.index)
    tx = run.tx[["node", "packet", "txIndex", "txTime", "psschRbStart", "psschRbLenTb"]].copy()
    tx["slot"] = np.round(tx.txTime / (slot / 1000.0)).astype(np.int64)
    tx["rbEnd"] = tx.psschRbStart + tx.psschRbLenTb
    tx = tx.drop_duplicates(["node", "packet", "txIndex"]).astype({"node": "int64", "txIndex": "int64"})
    own = collided.rename_axis("attempt").reset_index()[["attempt", "tx", "packet", "txIndex", "genTime"]].copy()
    own = own.astype({"tx": "int64", "txIndex": "int64"})
    own = own.merge(tx.rename(columns={"node": "tx"})[["tx", "packet", "txIndex", "slot", "psschRbStart", "rbEnd"]],
                    on=["tx", "packet", "txIndex"], how="inner")
    others = tx[["node", "slot", "psschRbStart", "rbEnd"]].rename(
        columns={"node": "k", "psschRbStart": "kStart", "rbEnd": "kEnd"})
    pairs = own.merge(others, on="slot")
    pairs = pairs[(pairs.k != pairs.tx) & (pairs.kStart < pairs.rbEnd) & (pairs.psschRbStart < pairs.kEnd)]
    if not len(pairs):
        return pd.Series(False, index=collided.index)
    # the last time the sender decoded the interferer before the collided packet was generated
    decoded = run.rx[run.rx.decoded == 1][["rxID", "txID", "rxTime"]].rename(
        columns={"rxID": "tx", "txID": "k", "rxTime": "heardAt"}).astype({"tx": "int64", "k": "int64"})
    decoded = decoded.sort_values("heardAt")
    pairs = pairs.sort_values("genTime")
    pairs = pd.merge_asof(pairs, decoded, left_on="genTime", right_on="heardAt", by=["tx", "k"],
                          direction="backward", allow_exact_matches=False)
    pairs["heard"] = pairs.heardAt.notna() & (pairs.genTime - pairs.heardAt <= SENSING_WINDOW)
    all_hidden = ~pairs.groupby("attempt").heard.any()
    return all_hidden.reindex(collided.index, fill_value=False)


def classify(attempts, run, drops, slot, jammer_windows):
    """One root cause per attempt, CAUSES order."""
    causes = pd.Series("never transmitted", index=attempts.index)
    drop_reason = drops.drop_duplicates("packet").set_index("packet").reason if len(drops) else pd.Series(dtype=object)
    not_sent = ~attempts.transmitted
    reason = attempts.packet.map(drop_reason)
    causes[not_sent & (reason == "oversize")] = "oversize drop"
    causes[not_sent & (reason == "intra-ue-conflict")] = "intra-UE conflict"
    causes[not_sent & (reason == "replaced")] = "replaced by a newer packet"
    sent = attempts.transmitted
    causes[sent & attempts.inTime] = "decoded in time"
    causes[sent & (attempts.decoded == 1) & ~attempts.inTime] = "late (decoded after the PDB)"
    lost = sent & (attempts.decoded == 0)
    causes[lost & (attempts.lossType == 1)] = "half duplex"
    causes[lost & (attempts.lossType == 0)] = "below sensitivity"
    causes[lost & (attempts.lossType == 2)] = "propagation"
    causes[lost & (attempts.lossType == 4)] = "injected burst"
    # A transmitted packet with no reception row at this receiver: the receiver was not logging
    # it (parked or outside the log window). Counted as never transmitted would be wrong
    causes[lost & attempts.lossType.isna()] = "propagation"
    collided = attempts[lost & (attempts.lossType == 3)]
    hidden = pd.Series(False, index=attempts.index)
    if len(collided):
        hidden.loc[collided.index] = hidden_collisions(run, collided, slot).to_numpy()
        causes[lost & (attempts.lossType == 3)] = "sensing-visible collision"
        causes[lost & (attempts.lossType == 3) & hidden] = "hidden-node collision"
    for start, stop in jammer_windows:
        jammed = lost & (attempts.lossType == 2) & (attempts.genTime >= start) & (attempts.genTime <= stop)
        causes[jammed] = "propagation"  # kept as propagation, the jammer flag below tells them apart
    attempts["cause"] = causes
    attempts["hiddenCollision"] = hidden
    return attempts


def pair_series(attempts):
    """Per (flow, tx, rx): PIR samples, DT samples and time-average AoI, in seconds.

    PIR: gap between consecutive decoded packets of the pair. DT: such a gap when at least one
    attempt of the pair generated between the two decoded packets was lost (Rolich et al.).
    AoI: area under the age sawtooth between the first and the last reception, over that span.
    """
    keys = ["flow", "tx", "rx"]
    a = attempts.sort_values(keys + ["genTime"]).reset_index(drop=True)
    a["ok"] = (a.decoded == 1).astype(int)
    # number of decoded attempts so far in the pair: a lost attempt with count m lies between
    # decoded packets m and m + 1
    a["successes"] = a.groupby(keys).ok.cumsum()
    lost = a[a.ok == 0].groupby(keys + ["successes"]).size().rename("lost")
    ok = a[a.ok == 1].copy()
    ok = ok.sort_values(keys + ["receptionTime"])
    same = (ok[keys].shift() == ok[keys]).all(axis=1)
    ok["gap"] = ok.receptionTime.diff().where(same)
    ok["delay"] = ok.receptionTime - ok.genTime
    ok["delayPrev"] = ok.delay.shift().where(same)
    ok["before"] = ok.successes - 1  # losses counted after the previous decoded packet
    ok = ok.join(lost, on=keys + ["before"])
    intervals = ok[ok.gap > 0]
    pir = intervals[["flow", "gap"]].rename(columns={"gap": "pir"})
    dt = intervals[intervals.lost.fillna(0) > 0][["flow", "gap"]].rename(columns={"gap": "dt"})
    intervals = intervals.assign(area=intervals.gap * intervals.delayPrev + intervals.gap ** 2 / 2,
                                 peak=intervals.gap + intervals.delayPrev)
    per_pair = intervals.groupby(keys).agg(area=("area", "sum"), span=("gap", "sum"), paoi=("peak", "mean"),
                                           n=("gap", "size")).reset_index()
    per_pair = per_pair[(per_pair.n >= 2) & (per_pair.span > 0)]
    aoi = per_pair.assign(aoi=per_pair.area / per_pair.span)[keys + ["aoi", "paoi"]]
    return pir.reset_index(drop=True), dt.reset_index(drop=True), aoi.reset_index(drop=True)


def occupancy(run, app, flows, slot, sim_time, subchannel, n_subchannels, warmup, nodes_active):
    """Share of subchannel-slots used by each class, per UE (CR) and over the channel."""
    tx = run.tx.merge(app[["packet", "flow"]], on="packet", how="left")
    tx = tx[tx.txTime >= warmup]
    tx["subchannels"] = np.ceil(tx.psschRbLen / subchannel)
    slots = (sim_time - warmup) / (slot / 1000.0)
    per_flow = tx.groupby("flow").subchannels.sum() / (slots * n_subchannels)
    per_ue = tx.groupby(["flow", "node"]).subchannels.sum() / (slots * n_subchannels)
    return per_flow.rename("occupancy"), per_ue.groupby("flow").mean().rename("cr_mean")


def reevaluation_counts(run, warmup):
    log = run.reevaluations
    log = log[log.time >= warmup] if len(log) else log
    if not len(log):
        return pd.DataFrame(columns=["priority", "kind", "checks", "reselections"])
    table = log.groupby(["priority", "kind"]).agg(checks=("reselected", "size"), reselections=("reselected", "sum"))
    return table.reset_index()


def compact_run(run_folder):
    """mr.Run with the two large logs read in compact types: a dense 15 s run has about 50 million
    reception rows, and several runs are summarised at the same time on the sweep host."""
    run = mr.Run(run_folder)
    rx_types = {"rxTime": "float64", "packetID": "int64", "distance": "float32", "txID": "int32", "rxID": "int32",
                "decoded": "int8", "lossType": "int8", "txIndex": "int16", "latency": "float32"}
    path = os.path.join(run_folder, "ReceivedLog.txt")
    if os.path.exists(path) and os.path.getsize(path) > 0:
        run._cache["rx"] = pd.read_csv(path, header=None, names=mr.RX_COLUMNS, usecols=list(rx_types), dtype=rx_types)
    tx_types = {"node": "int32", "packet": "int64", "genTime": "float64", "txIndex": "int16", "txTime": "float64",
                "psschRbStart": "int16", "psschRbLen": "int16", "psschRbLenTb": "int16"}
    path = os.path.join(run_folder, "phyDebugShort.txt")
    if os.path.exists(path) and os.path.getsize(path) > 0:
        run._cache["tx"] = pd.read_csv(path, header=None, names=mr.TX_COLUMNS, usecols=list(tx_types), dtype=tx_types)
    return run


def summarise(run_folder, trace_folder, warmup, max_distance, out, keep_attempts=False):
    run = compact_run(run_folder)
    app = read(run_folder, "AppTxLog.txt", APP_COLUMNS)
    flows = read(run_folder, "FlowMap.txt", FLOW_COLUMNS)
    drops = read(run_folder, "MacDropLog.txt", DROP_COLUMNS)
    nodes = pd.read_csv(os.path.join(run_folder, "NodeMap.txt"), header=None, names=["node", "role", "group", "position", "flows"])
    readme = dict(line.strip().split("=", 1) for line in open(os.path.join(run_folder, "simREADME.txt")) if "=" in line)
    sim_time = float(readme["simTime"])
    numerology = int(readme["numerology"])
    slot = 1.0 / (2 ** numerology)  # ms
    subchannel = int(readme["subchannel"])
    rbs = int(readme["bandwidth"].split("(")[1].split()[0])
    n_subchannels = rbs // subchannel
    jammer_windows = []
    if readme.get("jammer"):
        values = [float(v) for v in readme["jammer"].split(",")]
        jammer_windows.append((values[5], values[6]))

    positions = Positions(trace_folder, int(nodes.node.min()))
    attempts = attempts_table(run, app, flows, positions, max_distance, warmup, sim_time, slot)
    attempts = classify(attempts, run, drops, slot, jammer_windows)
    attempts["bin"] = pd.cut(attempts.distance, DISTANCE_BINS, right=False).apply(lambda b: b.left).astype(float)

    names = flows.set_index("flow").name
    os.makedirs(out, exist_ok=True)

    by_distance = attempts.groupby(["flow", "bin"]).agg(
        attempts=("decoded", "size"), pdr=("decoded", "mean"), qos_pdr=("inTime", "mean"),
        collision=("lossType", lambda s: (s == 3).mean()),
        hidden=("hiddenCollision", "mean")).reset_index()
    by_distance.to_csv(os.path.join(out, "by_distance.csv"), index=False)

    causes = attempts.groupby(["flow", "bin", "cause"]).size().rename("count").reset_index()
    causes.to_csv(os.path.join(out, "causes.csv"), index=False)

    pir, dt, aoi = pair_series(attempts)
    quantiles = [0.5, 0.9, 0.95, 0.99]
    summary = []
    cbr = run.cbr[run.cbr.time >= warmup]
    flow_occupancy, flow_cr = occupancy(run, app, flows, slot, sim_time, subchannel, n_subchannels, warmup, None)
    reevals = reevaluation_counts(run, warmup)
    transmissions = run.tx.merge(app[["packet", "flow", "priority"]], on="packet", how="left")
    transmissions = transmissions[transmissions.txTime >= warmup]
    for flow, group in attempts.groupby("flow"):
        flow_row = flows[flows.flow == flow].iloc[0]
        lost = group[group.decoded == 0]
        collisions = (group.lossType == 3).sum()
        row = {
            "flow": int(flow), "name": names[flow], "pqi": int(flow_row.pqi), "priority": int(flow_row.priority),
            "pdb_ms": float(flow_row.pdb), "per_target": float(flow_row.per),
            "packets": int(app[(app.flow == flow) & (app.genTime >= warmup)].shape[0]),
            "attempts": int(len(group)), "pdr": group.decoded.mean(), "qos_pdr": group.inTime.mean(),
            "per_measured": 1 - group.inTime.mean(),
            "per_met": bool(1 - group.inTime.mean() <= float(flow_row.per)),
            "collision_rate": collisions / len(group),
            "hncr": group.hiddenCollision.sum() / collisions if collisions else np.nan,
            "hnir": group.hiddenCollision.sum() / len(group),
            "latency_p50_ms": 1000 * group[group.decoded == 1].latency.median(),
            "latency_p99_ms": 1000 * group[group.decoded == 1].latency.quantile(0.99),
            "occupancy": float(flow_occupancy.get(flow, 0.0)), "cr_mean": float(flow_cr.get(flow, 0.0)),
            "transmissions": int((transmissions.flow == flow).sum()),
        }
        p = pir[pir.flow == flow].pir
        d = dt[dt.flow == flow].dt
        a = aoi[aoi.flow == flow]
        for q in quantiles:
            row["pir_p%d_ms" % (q * 100)] = 1000 * p.quantile(q) if len(p) else np.nan
            row["dt_p%d_ms" % (q * 100)] = 1000 * d.quantile(q) if len(d) else np.nan
        row["pir_mean_ms"] = 1000 * p.mean() if len(p) else np.nan
        row["dt_mean_ms"] = 1000 * d.mean() if len(d) else np.nan
        row["dt_count"] = int(len(d))
        row["aoi_mean_ms"] = 1000 * a.aoi.mean() if len(a) else np.nan
        row["paoi_mean_ms"] = 1000 * a.paoi.mean() if len(a) else np.nan
        prio = int(flow_row.priority)
        for kind, label in ((0, "reeval"), (1, "preempt")):
            sel = reevals[(reevals.priority == prio) & (reevals.kind == kind)]
            row[label + "_checks"] = int(sel.checks.sum())
            row[label + "_changes"] = int(sel.reselections.sum())
        for cause in CAUSES:
            row["cause_" + cause] = int((group.cause == cause).sum())
        summary.append(row)
    summary = pd.DataFrame(summary)
    summary["cbr_mean"] = cbr.cbr.mean() if len(cbr) else np.nan
    summary["cbr_p95"] = cbr.cbr.quantile(0.95) if len(cbr) else np.nan
    summary.to_csv(os.path.join(out, "flows.csv"), index=False)

    # CBR over time and the distributions behind the quantiles, for the plots
    if len(cbr):
        cbr.groupby((cbr.time // 0.1) * 0.1).cbr.agg(["mean", "max"]).reset_index().to_csv(
            os.path.join(out, "cbr_time.csv"), index=False)
    hist_edges = np.arange(0, 2.001, 0.01)
    rows = []
    for name, frame, column in (("pir", pir, "pir"), ("dt", dt, "dt")):
        for flow, g in frame.groupby("flow"):
            counts, _ = np.histogram(g[column].clip(upper=2.0), bins=hist_edges)
            rows += [(name, flow, e, c) for e, c in zip(hist_edges[:-1], counts) if c]
    pd.DataFrame(rows, columns=["metric", "flow", "edge_s", "count"]).to_csv(os.path.join(out, "histograms.csv"), index=False)
    aoi.to_csv(os.path.join(out, "aoi_pairs.csv"), index=False)
    if keep_attempts:
        attempts.to_csv(os.path.join(out, "attempts.csv.gz"), index=False)
    json.dump({"run": os.path.abspath(run_folder), "trace": os.path.abspath(trace_folder), "warmup": warmup,
               "max_distance": max_distance, "readme": readme}, open(os.path.join(out, "run.json"), "w"), indent=1)
    return summary


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("run")
    parser.add_argument("trace")
    parser.add_argument("--warmup", type=float, default=2.0, help="seconds left out at the start")
    parser.add_argument("--max-distance", type=float, default=1000.0, help="largest Tx-Rx distance counted")
    parser.add_argument("--out", default=None)
    parser.add_argument("--keep-attempts", action="store_true")
    args = parser.parse_args()
    out = args.out or os.path.join(args.run, "metrics")
    summary = summarise(args.run, args.trace, args.warmup, args.max_distance, out, args.keep_attempts)
    with pd.option_context("display.width", 200, "display.max_columns", 12):
        print(summary[["name", "pqi", "attempts", "pdr", "qos_pdr", "collision_rate", "hnir", "dt_mean_ms", "aoi_mean_ms"]])


if __name__ == "__main__":
    main()
